export type BuiltinRoleId = keyof typeof BUILTIN_ROLE_NAME_KEYS

export function getBuiltinRoleNameKey(roleId: string): string | undefined {
  return Object.prototype.hasOwnProperty.call(BUILTIN_ROLE_NAME_KEYS, roleId)
    ? BUILTIN_ROLE_NAME_KEYS[roleId as BuiltinRoleId]
    : undefined
}

